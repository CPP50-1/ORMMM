@pytest.mark.must
@pytest.mark.l1
class TestL1Foundation:
    def test_fields_are_descriptors(self, models):
        """spec 5.1 — Field implements the descriptor protocol."""
        field = models.Customer.__dict__.get("name")
        assert field is not None, "'name' is not declared on the Customer class itself"
        assert hasattr(field, "__get__"), "Field must implement __get__"
        assert hasattr(field, "__set__"), "Field must implement __set__ (data descriptor)"

    def test_values_are_per_instance_not_per_class(self, models):
        """spec 5.1 — the classic 'shared mutable state' bug."""
        a = models.Customer.create({"name": "Ada", "city": "Liege", "vip": True})
        b = models.Customer.create({"name": "Grace", "city": "Namur", "vip": False})
        assert a.name == "Ada"
        assert b.name == "Grace"
        a.write({"name": "Ada L."})
        assert b.name == "Grace", "writing on one record leaked onto another"

    def test_registry_is_populated_by_the_metaclass(self, orm, models):
        """spec 5.2 — models discoverable at runtime by name."""
        assert orm.registry_lookup("customer") is models.Customer
        assert orm.registry_lookup("order") is models.Order
        assert orm.registry_lookup("tag") is models.Tag
        assert orm.registry_lookup("does_not_exist") is None

    def test_tables_exist_with_expected_columns(self, orm, models):
        """spec 5.3 — CREATE TABLE generated from the declared fields."""
        rows = orm.raw_sql(
            "SELECT column_name, data_type FROM information_schema.columns WHERE table_name = %s",
            (orm.table_name(models.Customer),),
        )
        columns = {name: dtype for name, dtype in rows}
        assert columns, "no table found for Customer"
        assert "id" in columns
        assert "name" in columns
        assert "city" in columns
        assert "vip" in columns

    def test_column_types_match_field_types(self, orm, models):
        rows = orm.raw_sql(
            "SELECT column_name, data_type FROM information_schema.columns WHERE table_name = %s",
            (orm.table_name(models.Order),),
        )
        columns = {name: dtype for name, dtype in rows}
        assert "character varying" in columns["reference"] or columns["reference"] == "text"
        assert columns["amount"] in ("integer", "bigint", "smallint")


