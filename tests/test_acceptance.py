@pytest.mark.must
@pytest.mark.l2
class TestL2Crud:
    def test_create_returns_a_record_with_an_id(self, models):
        rec = models.Customer.create({"name": "Ada", "city": "Liege", "vip": True})
        assert rec.id is not None
        assert rec.name == "Ada"
        assert rec.vip is True

    def test_search_with_a_domain(self, models):
        models.Customer.create({"name": "Ada", "city": "Liege", "vip": True})
        models.Customer.create({"name": "Grace", "city": "Namur", "vip": False})
        found = models.Customer.search([("city", "=", "Liege")])
        assert len(found) == 1
        assert found[0].name == "Ada"

    def test_search_empty_domain_returns_all(self, models):
        for i in range(3):
            models.Customer.create({"name": f"C{i}", "city": "Liege", "vip": False})
        assert len(models.Customer.search([])) == 3

    def test_search_comparison_and_in_operators(self, models):
        for i in range(5):
            models.Order.create({"reference": f"SO{i}", "amount": i * 100})
        assert len(models.Order.search([("amount", ">", 150)])) == 3
        ids = [r.id for r in models.Order.search([])][:2]
        assert len(models.Order.search([("id", "in", ids)])) == 2

    def test_write_persists_to_the_database(self, models):
        rec = models.Customer.create({"name": "Ada", "city": "Liege", "vip": False})
        rec.write({"city": "Hasselt"})
        reloaded = models.Customer.browse(rec.id)
        assert reloaded.city == "Hasselt", "write() did not reach the database"

    def test_unlink_removes_the_row(self, models):
        rec = models.Customer.create({"name": "Ada", "city": "Liege", "vip": False})
        rec.unlink()
        assert len(models.Customer.search([])) == 0

    def test_sql_injection_is_neutralised(self, orm, models):
        """spec 5.3 SHOULD — parameterized queries, tested as an attack."""
        payload = "Robert'); DROP TABLE " + orm.table_name(models.Customer) + "; --"
        models.Customer.create({"name": payload, "city": "Liege", "vip": False})
        found = models.Customer.search([("city", "=", "Liege")])
        assert len(found) == 1
        assert found[0].name == payload, "the value was not stored verbatim"
        rows = orm.raw_sql(
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_name = %s",
            (orm.table_name(models.Customer),),
        )
        assert rows[0][0] == 1, "the table is gone — string-formatted SQL somewhere"


