@pytest.mark.should
@pytest.mark.l7
class TestL7Computed:
    def test_computed_value_is_correct(self, models):
        order = models.Order.create({"reference": "SO001", "amount": 100})
        assert order.amount_ttc == 121

    def test_computed_value_is_not_stale_after_a_write(self, models):
        order = models.Order.create({"reference": "SO001", "amount": 100})
        assert order.amount_ttc == 121
        order.write({"amount": 200})
        assert order.amount_ttc == 242, "computed value is stale — no invalidation"

    def test_computed_field_is_not_a_stored_column(self, orm, models):
        rows = orm.raw_sql(
            "SELECT column_name FROM information_schema.columns WHERE table_name = %s",
            (orm.table_name(models.Order),),
        )
        columns = {r[0] for r in rows}
        assert "amount_ttc" not in columns, (
            "amount_ttc is stored as a column — it must be derived by a method "
            "(storing it is a valid design, but not what this exercise checks)"
        )
