@pytest.mark.must
@pytest.mark.l4
class TestL4Relations:
    def test_one2many_reverse_lookup(self, models):
        customer = models.Customer.create({"name": "Ada", "city": "Liege", "vip": True})
        other = models.Customer.create({"name": "Grace", "city": "Namur", "vip": False})
        models.Order.create({"reference": "A1", "amount": 10, "customer": customer})
        models.Order.create({"reference": "A2", "amount": 20, "customer": customer})
        models.Order.create({"reference": "B1", "amount": 30, "customer": other})
        assert len(customer.orders) == 2
        assert {o.reference for o in customer.orders} == {"A1", "A2"}

    def test_one2many_is_empty_not_none(self, models):
        customer = models.Customer.create({"name": "Solo", "city": "Liege", "vip": False})
        assert len(customer.orders) == 0
        assert not customer.orders, "an empty recordset must be falsy"

    def test_many2many_junction_table_exists(self, orm):
        rows = orm.raw_sql(
            "SELECT COUNT(*) FROM information_schema.tables WHERE table_name = %s",
            (orm.m2m_table_name(),),
        )
        assert rows[0][0] == 1, "no junction table generated for Order.tags"

    def test_many2many_resolves_in_both_directions(self, models):
        tag_a = models.Tag.create({"name": "urgent"})
        tag_b = models.Tag.create({"name": "export"})
        order = models.Order.create({"reference": "SO001", "amount": 100})
        order.write({"tags": [tag_a, tag_b]})
        assert {t.name for t in order.tags} == {"urgent", "export"}
        assert order.id in [o.id for o in tag_a.orders], "reverse m2m accessor is broken"

    def test_many2many_is_shared_not_copied(self, models):
        tag = models.Tag.create({"name": "urgent"})
        o1 = models.Order.create({"reference": "SO001", "amount": 100})
        o2 = models.Order.create({"reference": "SO002", "amount": 200})
        o1.write({"tags": [tag]})
        o2.write({"tags": [tag]})
        assert len(tag.orders) == 2


