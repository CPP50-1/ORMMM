# L6 — N+1: measured, then fixed
# --------------------------------------------------------------------------


@pytest.mark.must
@pytest.mark.l6
class TestL6NPlusOne:
    def test_the_naive_pattern_really_is_n_plus_1(self, orm, models, dataset):
        """spec 5.6 — the problem must be *measurable*, not asserted."""
        with orm.without_prefetch():
            orders = models.Order.search([])
            orm.reset_queries()
            names = [order.customer.name for order in orders]
            naive = orm.query_count()
        assert len(names) == 50
        assert naive >= 50, (
            f"expected ~51 queries for the naive pattern, measured {naive}. "
            "Either without_prefetch() does not disable batching, or the "
            "counter does not count every statement."
        )

    def test_prefetch_collapses_the_query_count(self, orm, models, dataset):
        orders = models.Order.search([])
        len(orders)
        orm.reset_queries()
        orm.prefetch(orders, "customer")
        names = [order.customer.name for order in orders]
        fixed = orm.query_count()
        assert len(names) == 50
        assert fixed <= 3, f"prefetch issued {fixed} queries, expected <= 3: {orm.query_log()}"

    def test_the_improvement_is_at_least_tenfold(self, orm, models, dataset):
        with orm.without_prefetch():
            orders = models.Order.search([])
            orm.reset_queries()
            [order.customer.name for order in orders]
            naive = orm.query_count()

        orders = models.Order.search([])
        len(orders)
        orm.reset_queries()
        orm.prefetch(orders, "customer")
        [order.customer.name for order in orders]
        fixed = orm.query_count()

        assert naive >= 10 * fixed, f"naive={naive}, fixed={fixed} — not a real fix"

    @pytest.mark.should
    def test_prefetch_also_works_on_one2many(self, orm, models, dataset):
        customers = models.Customer.search([])
        len(customers)
        orm.reset_queries()
        orm.prefetch(customers, "orders")
        counts = [len(c.orders) for c in customers]
        assert sum(counts) == 50
        assert orm.query_count() <= 3, orm.query_log()


